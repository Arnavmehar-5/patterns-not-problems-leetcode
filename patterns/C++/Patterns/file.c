int main() {
    char name[100];
    
    printf("Enter a name (Letters/Spaces): ");
    if (fgets(name, sizeof(name), stdin) == NULL) return 1;
    name[strcspn(name, "\n")] = '\0'; // Remove newline character
    
    int len = strlen(name);
    printf("\n--- Negative Space Stencil Block ---\n\n");
    
    // Print row by row (Height = 5 lines)
    for (int r = 0; r < 5; r++) {
        printf("***"); // Left decorative border margin
        
        for (int i = 0; i < len; i++) {
            char ch = toupper((unsigned char)name[i]);
            
            if (ch >= 'A' && ch <= 'Z') {
                int letterIdx = ch - 'A';
                for (int c = 0; c < 5; c++) {
                    // INVERTED LOGIC: 
                    // If matrix contains a 1 (letter body), print a SPACE. 
                    // Otherwise, fill with a STAR.
                    if (alphabet[letterIdx][r][c] == 1) {
                        printf(" ");
                    } else {
                        printf("*");
                    }
                }
            } else if (ch == ' ') {
                // A whitespace input converts into a solid 5-star background block
                printf("*****");
            }
            
            // Solid star padding between letters to maintain the block canvas
            printf("**");
        }
        
        printf("*\n"); // Right decorative border finish
    }
    printf("\n");
    return 0;
}